"""Observed STX-W/Hike framing, independent of hardware and transport.

7E TYPE LENGTH16_BE PAYLOAD CRC16_BE 0D0A. LENGTH is total bytes minus two.
The CRC calculation is CRC-16/MODBUS; the framing and CRC byte order are not
Modbus RTU. The 512-byte limit is an implementation bound, not a device limit.
"""

from __future__ import annotations

from dataclasses import dataclass


MAX_FRAME_BYTES = 512
BytesLike = bytes | bytearray | memoryview


def _bytes(value: BytesLike) -> bytes:
    if not isinstance(value, (bytes, bytearray, memoryview)):
        raise TypeError('expected bytes, bytearray or memoryview')
    return bytes(value)


def _integer(value: int, low: int, high: int, name: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise TypeError(f'{name} must be an integer, not a boolean')
    if not low <= value <= high:
        raise ValueError(f'{name} must be in {low}..{high}')
    return int(value)


def crc16(data: BytesLike) -> int:
    """CRC-16/MODBUS: reflected 0xA001, initial 0xFFFF, no final XOR."""
    crc = 0xffff
    for value in _bytes(data):
        crc ^= value
        for _ in range(8):
            crc = (crc >> 1) ^ (0xa001 if crc & 1 else 0)
    return crc


def encode_frame(kind: int, payload: BytesLike) -> bytes:
    """Encode any byte-valued type without assigning it a command meaning."""
    kind = _integer(kind, 0, 255, 'kind')
    payload = _bytes(payload)
    if len(payload) + 8 > MAX_FRAME_BYTES:
        raise ValueError('frame exceeds the supported 512-byte limit')
    body = bytes([0x7e, kind]) + (len(payload) + 6).to_bytes(2, 'big') + payload
    return body + crc16(body).to_bytes(2, 'big') + b'\r\n'


@dataclass(frozen=True, slots=True)
class Frame:
    """A raw frame and its fields. Decoder results have validated framing/CRC.

    Constructing this value object directly does not validate its contents.
    Prefer Decoder for received bytes and encode_frame for generated bytes.
    """

    kind: int
    payload: bytes
    raw: bytes


class Decoder:
    """Incremental parser retaining at most 511 incomplete bytes.

    Embedded 7E/0D0A bytes are payload when the length says so. A plausible
    incomplete candidate is retained until completed or reset(); this pure
    core has no clock. The caller decides when an idle gap or disconnected
    transport warrants reset(). Unknown valid frame types are returned intact.
    """

    def __init__(self) -> None:
        self._buffer = bytearray()

    @property
    def buffered_bytes(self) -> int:
        return len(self._buffer)

    def reset(self) -> None:
        self._buffer.clear()

    def feed(self, data: BytesLike) -> list[Frame]:
        data = _bytes(data)  # Validate before modifying a partial candidate.
        frames = []
        for value in data:
            self._buffer.append(value)
            while self._buffer:
                marker = self._buffer.find(b'\x7e')
                if marker != 0:
                    del self._buffer[:marker if marker > 0 else len(self._buffer)]
                    continue
                if len(self._buffer) < 4:
                    break
                size = int.from_bytes(self._buffer[2:4], 'big') + 2
                if not 8 <= size <= MAX_FRAME_BYTES:
                    del self._buffer[0]
                    continue
                if len(self._buffer) < size:
                    break
                raw = bytes(self._buffer[:size])
                if raw[-2:] == b'\r\n' and crc16(raw[:-4]) == int.from_bytes(raw[-4:-2], 'big'):
                    frames.append(Frame(raw[1], raw[4:-4], raw))
                    del self._buffer[:size]
                else:
                    del self._buffer[0]
        return frames
